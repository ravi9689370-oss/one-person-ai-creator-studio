import { ActionButtonOutline } from "@/components/forms/action-button";
import { MediaUploadForm } from "@/components/forms/media-upload";
import { PageShell } from "@/components/ui/page-shell";
import { Card } from "@/components/ui/card";
import { EmptyState } from "@/components/ui/empty-state";
import { FilterPills, param } from "@/components/ui/filters";
import { prisma } from "@/lib/db";
import { pageCtx } from "@/lib/page";
import { formatDate } from "@/lib/utils";

export const metadata = { title: "Media Library" };

const KINDS = [
  { value: "all", label: "All" },
  { value: "video", label: "Video" },
  { value: "audio", label: "Audio" },
  { value: "image", label: "Images" },
  { value: "document", label: "Documents" },
  { value: "file", label: "Other" },
];

export default async function MediaLibraryPage({ searchParams }: { searchParams: { kind?: string } }) {
  const ctx = await pageCtx();
  const kind = param(searchParams.kind) ?? "all";
  const assets = await prisma.mediaAsset.findMany({
    where: { workspaceId: ctx.workspaceId, ...(kind !== "all" ? { kind } : {}) },
    orderBy: { createdAt: "desc" },
    take: 60,
  });

  return (
    <PageShell title="Media Library" subtitle="Private storage for uploads and generated assets - new media is always private and generated by an agent is never assumed to be publishable.">
      <div className="grid grid-cols-1 gap-6 lg:grid-cols-3">
        <div className="space-y-6 lg:col-span-2">
          <FilterPills base="/workspace/media-library" param="kind" current={kind} options={KINDS} />
          <Card title={`Assets (${assets.length})`} dense>
            {assets.length === 0 ? (
              <EmptyState
                title="No media here yet"
                body="Upload b-roll, audio takes, or reference files. Outputs from agents land here too."
              />
            ) : (
              <ul className="divide-y divide-slate-100 dark:divide-[#232b4d]">
                {assets.map((a) => (
                  <li key={a.id} className="flex items-center justify-between gap-3 px-4 py-3">
                    <div className="min-w-0">
                      <p className="truncate text-sm font-semibold text-slate-800 dark:text-slate-100">{a.title}</p>
                      <p className="text-[11px] text-slate-400">
                        {a.kind} · {a.visibility} · {a.sizeBytes ? `${Math.ceil(a.sizeBytes / 1024)} KB` : "—"}{a.mime ? ` · ${a.mime}` : ""} · {formatDate(a.createdAt)}
                      </p>
                      {a.path && <p className="truncate text-[11px] text-slate-400">path: {a.path}</p>}
                    </div>
                    <div className="flex shrink-0 items-center gap-2">
                      <a href={`/api/media/${a.id}/raw`} className="rounded-lg border border-slate-300 bg-white px-3 py-1.5 text-xs font-semibold text-slate-700 hover:border-indigo-300 hover:text-indigo-700 dark:border-[#2c3560] dark:bg-[#16204a] dark:text-slate-200">Open</a>
                      <ActionButtonOutline
                        endpoint={`/api/media?id=${a.id}`}
                        method="DELETE"
                        label="Delete"
                        confirmText="Delete this asset? Existing output references to it will fail verification."
                        className="border border-rose-200 bg-rose-50 text-rose-700 hover:border-rose-300 dark:border-rose-900/50 dark:bg-rose-950/30 dark:text-rose-300"
                      />
                    </div>
                  </li>
                ))}
              </ul>
            )}
          </Card>
        </div>
        <Card title="Upload an asset">
          <MediaUploadForm />
          <p className="mt-3 text-[11px] text-slate-400 dark:text-slate-500">
            Uploads are stored under your workspace path and served back through an authenticated route.
          </p>
        </Card>
      </div>
    </PageShell>
  );
}
