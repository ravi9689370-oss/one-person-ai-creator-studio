import Link from "next/link";
import { PageShell } from "@/components/ui/page-shell";
import { Card } from "@/components/ui/card";
import { prisma } from "@/lib/db";
import { pageCtx } from "@/lib/page";
import { formatDate, formatMoney } from "@/lib/utils";

export const metadata = { title: "Analytics" };
const DAY = 86400_000;

export default async function AnalyticsPage() {
  const ctx = await pageCtx();
  const since = new Date(Date.now() - 30 * DAY);
  const workspace = await prisma.workspace.findUnique({ where: { id: ctx.workspaceId }, select: { currency: true } });
  const currency = workspace?.currency ?? "USD";
  const [posts, metrics, revenueAgg, orders, snapshots] = await Promise.all([
    prisma.publishedPost.findMany({ where: { workspaceId: ctx.workspaceId, publishedAt: { gte: since } }, orderBy: { publishedAt: "desc" }, take: 20 }),
    prisma.postMetric.findMany({ where: { publishedPost: { workspaceId: ctx.workspaceId } }, orderBy: { capturedAt: "desc" }, take: 60 }),
    prisma.revenueRecord.aggregate({ where: { workspaceId: ctx.workspaceId, kind: "sale", occurredAt: { gte: since } }, _sum: { amountCents: true } }),
    prisma.order.findMany({ where: { workspaceId: ctx.workspaceId, status: "paid" }, select: { amountCents: true, createdAt: true } }),
    prisma.analyticsSnapshot.findMany({ where: { workspaceId: ctx.workspaceId }, orderBy: { createdAt: "desc" }, take: 5 }),
  ]);
  const views = metrics.reduce((sum, m) => sum + (m.views ?? 0), 0);
  const likes = metrics.reduce((sum, m) => sum + (m.likes ?? 0), 0);

  return (
    <PageShell title="Analytics" subtitle="Only metrics that were actually captured are shown - projections are explicit, never passed off as actuals." >
      <div className="grid grid-cols-1 gap-4 sm:grid-cols-3">
        <Card><p className="text-[11px] font-semibold uppercase tracking-wide text-slate-400">Views (sampled)</p><p className="mt-1 text-3xl font-bold">{views.toLocaleString()}</p><p className="mt-1 text-xs text-slate-500">sum of captured metrics · whenever metrics exist</p></Card>
        <Card><p className="text-[11px] font-semibold uppercase tracking-wide text-slate-400">Engagements</p><p className="mt-1 text-3xl font-bold">{likes.toLocaleString()}</p><p className="mt-1 text-xs text-slate-500">likes recorded on published posts</p></Card>
        <Link href="/analytics/revenue" className="card block p-4 transition hover:shadow-pop"><p className="text-[11px] font-semibold uppercase tracking-wide text-slate-400">Verified revenue (30d)</p><p className="mt-1.5 text-3xl font-bold">{formatMoney(revenueAgg._sum.amountCents ?? 0, currency)}</p><p className="mt-1 text-xs text-slate-500">{orders.length} paid orders</p></Link>
      </div>

      <div className="grid grid-cols-1 gap-6 lg:grid-cols-2">
        <Card title="Content performance (published)">
          {posts.length === 0 ? (
            <p className="text-xs text-slate-400">No published posts in the last 30 days yet - performance rows appear as soon as real publishing happens.</p>
          ) : (
            <ul className="divide-y divide-slate-100 dark:divide-[#232b4d]">
              {posts.map((p) => {
                const m = metrics.find((mm) => mm.publishedPostId === p.id);
                return (
                  <li key={p.id} className="flex items-center justify-between gap-3 py-2.5 first:pt-0 last:pb-0">
                    <span className="truncate text-sm">{p.platform} · {p.caption?.slice(0, 40) ?? "(external post)"}</span>
                    <span className="text-xs text-slate-400">{m ? `${m.views ?? 0} views` : "no metrics"}</span>
                  </li>
                );
              })}
            </ul>
          )}
        </Card>
        <Card title="Stored snapshots">
          {snapshots.length === 0 ? (
            <p className="text-xs text-slate-400">Snapshots (content / revenue / languages) are generated by the analytics.report agent and stored here with their source label.</p>
          ) : (
            <ul className="space-y-2 text-xs">
              {snapshots.map((s) => (
                <li key={s.id} className="flex items-center justify-between gap-2">
                  <span className="font-semibold text-slate-700 dark:text-slate-200">{s.scope}{s.channel ? ` · ${s.channel}` : ""}</span>
                  <span className="text-slate-400">source: {s.source} · {formatDate(s.createdAt)}</span>
                </li>
              ))}
            </ul>
          )}
        </Card>
      </div>
    </PageShell>
  );
}
