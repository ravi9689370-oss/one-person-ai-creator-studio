/**
 * Provider adapter layer.
 *
 * Every adapter exposes its real configuration state so the UI can report:
 *   - "operational"   -> configured AND verified usable
 *   - "configured"    -> credentials present, not yet verified
 *   - "mock"          -> development fixture provider (outcomes clearly labeled)
 *
 * Mock outputs are always tagged `mock: true` and surfaced in the UI as
 * DEVELOPMENT fixtures. They are never presented as real generated assets.
 */
import { providerEnv } from "@/lib/env";

export type ProviderMode = "real" | "mock";

export type MockMeta = { mock: true; provider: "development-fixture" };

export type LlmMessage = { role: "system" | "user" | "assistant"; content: string };

export type LlmResult = {
  mode: ProviderMode;
  provider: string;
  text: string;
  usage?: { inputTokens?: number; outputTokens?: number };
  mock?: MockMeta;
};

export class ProviderError extends Error {
  provider: string;
  constructor(provider: string, message: string) {
    super(message);
    this.provider = provider;
  }
}

export function llmConfigured(): { provider: string; configured: boolean } {
  const env = providerEnv();
  if (env.anthropicApiKey) return { provider: "anthropic", configured: true };
  if (env.openaiApiKey) return { provider: "openai", configured: true };
  return { provider: "mock", configured: false };
}

/** The labeled development fixture LLM. Deterministic, template-based. */
export function mockLlm(system: string, user: string): LlmResult {
  const wantsJson = system.includes("JSON") || user.includes("JSON");
  const topic =
    /topic[:\s]*["“]?([^"”\n.]+)["”.\n]/i.exec(user)?.[1]?.trim() ??
    /(["“])([^"”]{8,80})\1/.exec(user)?.[2]?.trim() ??
    "your topic";
  const body =
    `# ${topic}\n\n` +
    `[DEVELOPMENT FIXTURE — generated by the local mock LLM. Configure ANTHROPIC_API_KEY or OPENAI_API_KEY for real output.]\n\n` +
    `Hook: Stop scrolling — this changes how you think about ${topic.toLowerCase()}.\n\n` +
    `1. Start with the viewer's problem: they keep producing, but growth stalls.\n` +
    `2. Show the shift: publish in one system, not ten tabs.\n` +
    `3. Demonstrate with evidence: walk through the workflow result.\n` +
    `4. Give the viewer one action to take today.\n\n` +
    `Call to action: Save this, then build your first workflow this week.`;
  const text = wantsJson
    ? JSON.stringify({
        hook: `Stop scrolling — this changes how you think about ${topic.toLowerCase()}.`,
        sections: [
          { heading: "Problem", beats: "Viewer produces daily but growth stalls; they drown in tools." },
          { heading: "Shift", beats: "One system beats ten tabs; show the pipeline." },
          { heading: "Proof", beats: "Walk through the actual workflow result." },
          { heading: "Action", beats: "Viewer commits to building one workflow today." },
        ],
        cta: "Save this, then build your first workflow this week.",
        _mock: true,
      })
    : body;
  return {
    mode: "mock",
    provider: "development-fixture",
    text,
    usage: { inputTokens: Math.ceil((system.length + user.length) / 6), outputTokens: Math.ceil(text.length / 6) },
    mock: { mock: true, provider: "development-fixture" },
  };
}

const TIMEOUT_MS = 60_000;

async function fetchWithTimeout(url: string, init: RequestInit & { timeoutMs?: number }): Promise<Response> {
  const ctrl = new AbortController();
  const timer = setTimeout(() => ctrl.abort(), init.timeoutMs ?? TIMEOUT_MS);
  try {
    return await fetch(url, { ...init, signal: ctrl.signal });
  } finally {
    clearTimeout(timer);
  }
}

export async function callLlm(opts: {
  system: string;
  user: string;
  maxTokens?: number;
  temperature?: number;
  mock?: boolean; // force the labeled fixture (tests)
}): Promise<LlmResult> {
  const env = providerEnv();
  if (opts.mock) return mockLlm(opts.system, opts.user);

  if (env.anthropicApiKey) {
    try {
      const res = await fetchWithTimeout("https://api.anthropic.com/v1/messages", {
        method: "POST",
        headers: {
          "content-type": "application/json",
          "x-api-key": env.anthropicApiKey,
          "anthropic-version": "2023-06-01",
        },
        body: JSON.stringify({
          model: "claude-sonnet-4-20250514",
          max_tokens: opts.maxTokens ?? 2000,
          temperature: opts.temperature ?? 0.7,
          system: opts.system,
          messages: [{ role: "user", content: opts.user }],
        }),
        timeoutMs: TIMEOUT_MS,
      });
      if (!res.ok) {
        const detail = await res.text().catch(() => "");
        throw new ProviderError("anthropic", `HTTP ${res.status}: ${detail.slice(0, 300)}`);
      }
      const json = (await res.json()) as {
        content?: { type: string; text?: string }[];
        usage?: { input_tokens?: number; output_tokens?: number };
      };
      const text = (json.content ?? [])
        .filter((c) => c.type === "text")
        .map((c) => c.text ?? "")
        .join("\n");
      return {
        mode: "real",
        provider: "anthropic",
        text,
        usage: { inputTokens: json.usage?.input_tokens, outputTokens: json.usage?.output_tokens },
      };
    } catch (e) {
      // Real misconfiguration/timeouts must not be masked as success.
      if (e instanceof ProviderError) throw e;
      throw new ProviderError("anthropic", e instanceof Error ? e.message : "network error");
    }
  }

  if (env.openaiApiKey) {
    try {
      const res = await fetchWithTimeout("https://api.openai.com/v1/chat/completions", {
        method: "POST",
        headers: { "content-type": "application/json", authorization: `Bearer ${env.openaiApiKey}` },
        body: JSON.stringify({
          model: "gpt-4o-mini",
          max_tokens: opts.maxTokens ?? 2000,
          temperature: opts.temperature ?? 0.7,
          messages: [
            { role: "system", content: opts.system },
            { role: "user", content: opts.user },
          ],
        }),
        timeoutMs: TIMEOUT_MS,
      });
      if (!res.ok) {
        const detail = await res.text().catch(() => "");
        throw new ProviderError("openai", `HTTP ${res.status}: ${detail.slice(0, 300)}`);
      }
      const json = (await res.json()) as {
        choices?: { message?: { content?: string } }[];
        usage?: { prompt_tokens?: number; completion_tokens?: number };
      };
      const text = json.choices?.[0]?.message?.content ?? "";
      return {
        mode: "real",
        provider: "openai",
        text,
        usage: { inputTokens: json.usage?.prompt_tokens, outputTokens: json.usage?.completion_tokens },
      };
    } catch (e) {
      if (e instanceof ProviderError) throw e;
      throw new ProviderError("openai", e instanceof Error ? e.message : "network error");
    }
  }

  // No credentials: labeled development fixture.
  return mockLlm(opts.system, opts.user);
}
